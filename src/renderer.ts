import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
import { RobotState } from './state';
const AXES=[new THREE.Vector3(1,0,0),new THREE.Vector3(0,0,1),new THREE.Vector3(0,0,-1),new THREE.Vector3(0,-1,0),new THREE.Vector3(0,0,-1),new THREE.Vector3(0,-1,0)];
export async function createRenderer(state:RobotState){
 const canvas=document.querySelector<HTMLCanvasElement>('#robot-canvas')!;
 const viewport=canvas.parentElement!;
 const loading=document.querySelector<HTMLElement>('#loading-state')!;
 const renderer=new THREE.WebGLRenderer({canvas,antialias:true,alpha:false,powerPreference:'high-performance'});
 renderer.setPixelRatio(Math.min(window.devicePixelRatio,2));
 renderer.setClearColor(0xe9edf2);
 renderer.outputColorSpace=THREE.SRGBColorSpace;
 renderer.toneMapping=THREE.ACESFilmicToneMapping;
 renderer.toneMappingExposure=1.12;
 renderer.shadowMap.enabled=true;
 renderer.shadowMap.type=THREE.PCFSoftShadowMap;
 const scene=new THREE.Scene();
 const pmrem=new THREE.PMREMGenerator(renderer);
 const environment=new RoomEnvironment();
 scene.environment=pmrem.fromScene(environment,.04).texture;
 environment.dispose();pmrem.dispose();
 scene.add(new THREE.HemisphereLight(0xffffff,0x9aa5b5,2.0));
 const key=new THREE.DirectionalLight(0xffffff,3.1);key.position.set(3,5,2);key.castShadow=true;key.shadow.mapSize.set(1024,1024);key.shadow.camera.left=-2;key.shadow.camera.right=2;key.shadow.camera.top=2;key.shadow.camera.bottom=-2;key.shadow.normalBias=.015;key.shadow.bias=-.0003;scene.add(key);
 const fill=new THREE.DirectionalLight(0xbedbff,1.2);fill.position.set(-3,2,-3);scene.add(fill);
 const camera=new THREE.PerspectiveCamera(35,1,.01,100);
 const controls=new OrbitControls(camera,canvas);controls.enableDamping=true;controls.dampingFactor=.08;controls.enablePan=false;controls.minPolarAngle=.1;controls.maxPolarAngle=Math.PI*.495;controls.rotateSpeed=.65;controls.zoomSpeed=.75;
 let frameHeight=1.8;
 let lastAspect=0;
 const cameraDirection=new THREE.Vector3(1.15,.48,1.65).normalize();
 const resetCamera=()=>{const aspect=viewport.clientWidth/viewport.clientHeight;const fitHeight=frameHeight/2/Math.tan(THREE.MathUtils.degToRad(camera.fov/2));const fitWidth=frameHeight*.67/2/Math.tan(THREE.MathUtils.degToRad(camera.fov/2))/aspect;const distance=Math.max(fitHeight,fitWidth)*1.16;camera.position.copy(controls.target).addScaledVector(cameraDirection,distance);controls.minDistance=distance*.55;controls.maxDistance=distance*2.2;controls.update();};
 document.querySelector('#view-reset')!.addEventListener('click',resetCamera);
 const resize=()=>{const width=viewport.clientWidth,height=viewport.clientHeight;if(!width||!height)return;camera.aspect=width/height;camera.updateProjectionMatrix();renderer.setSize(width,height,false);if(lastAspect===0 || (lastAspect<.8)!==(camera.aspect<.8))resetCamera();lastAspect=camera.aspect;};
 const observer=new ResizeObserver(resize);observer.observe(viewport);resize();
 renderer.setAnimationLoop(()=>{controls.update();renderer.render(scene,camera);});
 const gltf=await new GLTFLoader().loadAsync('/robot.glb');
 const model=gltf.scene;
 model.traverse(object=>{if(object instanceof THREE.Mesh){object.castShadow=true;object.receiveShadow=true;const materials=Array.isArray(object.material)?object.material:[object.material];materials.forEach(material=>{if(material instanceof THREE.MeshStandardMaterial)material.emissive.set(0x000000);});}});
 scene.add(model);model.updateMatrixWorld(true);
 const bounds=new THREE.Box3().setFromObject(model);const center=bounds.getCenter(new THREE.Vector3());const size=bounds.getSize(new THREE.Vector3());
 frameHeight=size.y;
 controls.target.set(center.x,center.y+.025,center.z);
 const floor=new THREE.Mesh(new THREE.PlaneGeometry(200,200),new THREE.ShadowMaterial({color:0x34445a,opacity:.14}));floor.rotation.x=-Math.PI/2;floor.position.set(center.x,bounds.min.y-.001,center.z);floor.receiveShadow=true;scene.add(floor);
 const grid=new THREE.GridHelper(12,48,0xb9c5d0,0xd1d9e1);grid.position.set(center.x,bounds.min.y-.002,center.z);(grid.material as THREE.Material).transparent=true;(grid.material as THREE.Material).opacity=.32;scene.add(grid);
 key.target.position.copy(center);scene.add(key.target);
 const pivots=AXES.map((_,i)=>{const pivot=model.getObjectByName(`J${i+1}_Pivot`);if(!pivot)throw new Error(`Joint ${i+1} is missing from the robot model.`);return pivot;});
 state.subscribe(values=>{values.forEach((value,i)=>pivots[i].quaternion.setFromAxisAngle(AXES[i],THREE.MathUtils.degToRad(value)));model.updateMatrixWorld(true);});
 resetCamera();loading.hidden=true;canvas.dataset.loaded='true';
 return {scene,model,pivots,renderer,camera,controls,resize,resetCamera};
}
